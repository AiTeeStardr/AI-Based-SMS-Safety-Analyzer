urls = [
    "bit.ly/claim-th", "line.me/ti/p/@scam88", "peath-refund.com", "kbank-auth.xyz",
    "scb-secure.site", "flash-express-th.cc", "loan-quick-money.net", "spin99-bonus.vip",
    "tinyurl.com/parcel-chk", "t.co/claim5000", "free-credit100.club", "police-cyber.org"
]

data = []

# สร้างชุดข้อมูล Scam (350 ตัวอย่าง)
for i in range(350):
    tmpl = random.choice(scam_templates)
    url = random.choice(urls)
    num = str(random.randint(1000, 9999))
    text = tmpl.format(url=url, num=num)
    data.append({"text": text, "label": 1, "category": "มิจฉาชีพ/หลอกลวง (Scam)"})

# สร้างชุดข้อมูล Ham (350 ตัวอย่าง)
for i in range(350):
    tmpl = random.choice(ham_templates)
    otp = str(random.randint(100000, 999999))
    ref = f"{chr(random.randint(65, 90))}{chr(random.randint(65, 90))}{random.randint(10, 99)}"
    num = str(random.randint(10, 99))
    date = f"{random.randint(1, 28)}/10/2569"
    text = tmpl.format(otp=otp, ref=ref, num=num, date=date)
    data.append({"text": text, "label": 0, "category": "ข้อความปกติ/ปลอดภัย (Ham)"})

df = pd.DataFrame(data)
# สับเปลี่ยนแถวสุ่ม
df = df.sample(frac=1, random_state=42).reset_index(drop=True)

df.to_csv("thai_scam_sms_dataset.csv", index=False, encoding="utf-8-sig")
print(f"สร้างไฟล์ thai_scam_sms_dataset.csv สำเร็จ! จำนวนทั้งหมด: {len(df)} แถว")
